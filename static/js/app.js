    const txRegex = /def\s+(?:process_user_transaction_data|process_transaction_data|process_transaction)\s*\(\s*([a-zA-Z_0-9]+)\s*,\s*([a-zA-Z_0-9]+)\s*\)\s*:\s*\n\s*([a-zA-Z_0-9]+)\s*=\s*\1\s*-\s*\2\s*\n\s*return\s+\3/;
